// Rebuilds the results tables in benchmarks/README.md from benchmarks/results/*.json.
//   mise run bench:report
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

interface Result {
  variant: string;
  particles: number;
  status: string;
  setupMs?: number;
  memoryMB?: number;
  eventsPerSecond?: number;
  framesPerSecond?: number;
}
interface Report {
  runner: string;
  runtime: string;
  os: string;
  cpus: number;
  warmupSeconds: number;
  measureSeconds: number;
  results: Result[];
}

const dir = 'benchmarks/results';
const reports: Report[] = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .sort()
  .map((f) => JSON.parse(readFileSync(`${dir}/${f}`, 'utf8')) as Report);

const LABELS: Record<string, string> = {
  'java-stats': 'Java (with statistics)',
  'java-physics': 'Java (physics only)',
  'web-node': 'Web engine (Node)',
  'web-browser': 'Web engine (browser)',
};
const variants = [...new Set(reports.flatMap((r) => r.results.map((x) => x.variant)))];
const counts = [...new Set(reports.flatMap((r) => r.results.map((x) => x.particles)))].sort(
  (a, b) => a - b,
);
const find = (variant: string, n: number) =>
  reports.flatMap((r) => r.results).find((x) => x.variant === variant && x.particles === n);

const fmt = (value: number | undefined, digits = 0) => {
  if (value === undefined) return '–';
  // Small values keep two significant figures rather than rounding to 0.
  if (value !== 0 && Math.abs(value) < 10 ** -digits * 10) {
    return value.toLocaleString('en-US', { maximumSignificantDigits: 2 });
  }
  return value.toLocaleString('en-US', {
    maximumFractionDigits: digits,
    minimumFractionDigits: digits,
  });
};
const cell = (r: Result | undefined, pick: (r: Result) => string) =>
  !r ? '–' : r.status === 'ok' ? pick(r) : r.status.startsWith('skipped') ? '–' : r.status;

function table(title: string, pick: (r: Result) => string): string {
  const header = `| Particles | ${variants.map((v) => LABELS[v] ?? v).join(' | ')} |`;
  const rule = `| ---: | ${variants.map(() => '---:').join(' | ')} |`;
  const rows = counts.map(
    (n) => `| ${fmt(n)} | ${variants.map((v) => cell(find(v, n), pick)).join(' | ')} |`,
  );
  return [`### ${title}`, '', header, rule, ...rows].join('\n');
}

const ratioRows = counts.map((n) => {
  const web = find('web-node', n);
  const javaPhysics = find('java-physics', n);
  const javaStats = find('java-stats', n);
  const ratio = (java: Result | undefined) =>
    web?.status === 'ok' && java?.status === 'ok'
      ? `${fmt(web.eventsPerSecond! / java.eventsPerSecond!, 2)}×`
      : '–';
  return `| ${fmt(n)} | ${ratio(javaPhysics)} | ${ratio(javaStats)} |`;
});

const environments = reports
  .map(
    (r) =>
      `- **${r.runner}:** ${r.runtime}; ${r.os}; ${r.cpus} CPUs; warm-up ${r.warmupSeconds} s, measured ${r.measureSeconds} s.`,
  )
  .join('\n');

const generated = [
  '<!-- results:start (generated by `mise run bench:report`; edit the JSON, not this) -->',
  '',
  environments,
  '',
  table('Events per second', (r) => fmt(r.eventsPerSecond)),
  '',
  table('Frames per second (the app shows about 27)', (r) => fmt(r.framesPerSecond, 1)),
  '',
  table('Setup time, ms (building the simulation and predicting every initial event)', (r) =>
    fmt(r.setupMs),
  ),
  '',
  table('Memory after setup, MB', (r) => fmt(r.memoryMB)),
  '',
  '### Web engine speed relative to Java (events per second)',
  '',
  '| Particles | vs Java physics only | vs Java with statistics |',
  '| ---: | ---: | ---: |',
  ...ratioRows,
  '',
  '<!-- results:end -->',
].join('\n');

const path = 'benchmarks/README.md';
const readme = readFileSync(path, 'utf8');
const start = readme.indexOf('<!-- results:start');
const end = readme.indexOf('<!-- results:end -->') + '<!-- results:end -->'.length;
if (start < 0 || end < start) throw new Error(`${path} is missing the results markers`);
writeFileSync(path, readme.slice(0, start) + generated + readme.slice(end));
console.log(`Updated ${path}`);
